import { expect, it } from 'vitest'
import { elapsed, mergeTime, point, SettlementTime } from './settlement-time.js'

it('keeps an empty clock distinct from a single qualified fact', () => {
  const time = new SettlementTime()
  expect(time.snapshot().get('a')).toBeUndefined()
  expect(elapsed(null)).toBe(0)
  time.add('a', 0, 0)
  expect(time.snapshot().get('a')).toEqual(point(0, 0))
  expect(elapsed(time.snapshot().get('a')!)).toBe(0)
})
it('retracts both endpoints when pending allocation changes participants', () => {
  const time = new SettlementTime()
  time.add('a', 2000, 1900)
  time.replace('early', ['a'], 1000, 900)
  time.replace('late', ['a'], 4000, 3900)
  expect(time.snapshot().get('a')).toMatchObject({ first: 1000, last: 4000 })
  time.replace('early', ['b'], 1000, 900)
  time.replace('late', ['b'], 4000, 3900)
  expect(time.snapshot().get('a')).toEqual(point(2000, 1900))
  expect(elapsed(time.snapshot().get('b')!)).toBe(3000)
  time.replace('early', [], 1000, 900)
  time.replace('late', [], 4000, 3900)
  expect(time.snapshot().has('b')).toBe(false)
})
it('uses packet time only when every remaining qualified fact has it', () => {
  const time = new SettlementTime()
  time.add('a', 1000, 900)
  time.add('a', 3000, 2800)
  expect(elapsed(time.snapshot().get('a')!)).toBe(1900)
  time.replace('unknown', ['a'], 2000)
  expect(elapsed(time.snapshot().get('a')!)).toBe(2000)
  time.replace('unknown', [], 2000)
  expect(elapsed(time.snapshot().get('a')!)).toBe(1900)
})
it('folds finished and sealed contributions without losing their ranges', () => {
  const time = new SettlementTime()
  time.add('a', 2000, 1900)
  time.replace('early', ['a'], 1000, 900)
  time.replace('late', ['a'], 3000, 2900)
  const before = time.snapshot()
  time.finish('early')
  time.finish('early')
  time.seal()
  expect(time.snapshot()).toEqual(before)
  expect(time.snapshot().get('a')).toMatchObject({ first: 1000, last: 3000 })
})
it('merges actor bounds without mutating the source ranges', () => {
  const first = point(1000, 900),
    last = point(2000, 1800)
  expect(elapsed(mergeTime(first, last))).toBe(900)
  expect(first).toEqual(point(1000, 900))
  expect(last).toEqual(point(2000, 1800))
})
